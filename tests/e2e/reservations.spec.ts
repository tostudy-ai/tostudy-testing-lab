import { expect, test } from '@playwright/test';
test('reserve, reject overlap, reject another user and cancel as owner', async ({ page }) => {
  const errors:string[]=[]; page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/');
  await expect(page.getByRole('heading',{name:'Reserve um espaço para trabalhar.'})).toBeVisible();
  await expect(page.getByLabel('Sala')).toHaveValue('cedar');
  await page.getByLabel('Início').fill('2030-05-20T10:00');
  await page.getByLabel('Fim').fill('2030-05-20T11:00');
  await page.getByRole('button',{name:'Reservar sala'}).click();
  await expect(page.getByRole('status')).toHaveText('Reserva criada.');
  await expect(page.getByTestId('booking')).toHaveCount(1);
  await page.getByRole('button',{name:'Reservar sala'}).click();
  await expect(page.getByRole('status')).toHaveText('Esse horário já está reservado.');
  await page.getByLabel('Usuário de demonstração').selectOption('bob');
  await expect(page.getByRole('status')).toHaveText('Usuário alterado.');
  await page.getByRole('button',{name:'Cancelar reserva'}).click();
  await expect(page.getByRole('status')).toHaveText('Você só pode cancelar suas reservas.');
  await expect(page.getByTestId('booking')).toHaveCount(1);
  await page.screenshot({path:'evidence/reservations-desktop.png',fullPage:true});
  await page.getByLabel('Usuário de demonstração').selectOption('alice');
  await expect(page.getByRole('status')).toHaveText('Usuário alterado.');
  await page.getByRole('button',{name:'Cancelar reserva'}).click();
  await expect(page.getByRole('status')).toHaveText('Reserva cancelada.');
  await expect(page.getByText('Nenhuma reserva por aqui.')).toBeVisible();
  await page.setViewportSize({width:390,height:844});
  await expect(page.getByRole('button',{name:'Reservar sala'})).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await page.screenshot({path:'evidence/reservations-mobile.png',fullPage:true});
  expect(errors).toEqual([]);
});
